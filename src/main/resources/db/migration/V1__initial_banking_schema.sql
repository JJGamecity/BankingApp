-- IF NOT EXISTS allows adopting the existing Hibernate-managed local schema without deleting data.
-- Flyway baselines that schema at version 0, so this migration still runs.
CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) UNIQUE,
    username varchar(255) UNIQUE,
    password varchar(255),
    google_subject varchar(255) UNIQUE,
    first_name varchar(255),
    last_name varchar(255),
    dob date,
    credit_score integer
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS google_subject varchar(255);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_google_subject ON users (google_subject);

CREATE TABLE IF NOT EXISTS staff_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    role varchar(255) NOT NULL CHECK (role IN ('ADMIN', 'BANK_REPRESENTATIVE')),
    created_by varchar(255),
    created_at timestamp(6) with time zone
);
ALTER TABLE staff_accounts ADD COLUMN IF NOT EXISTS created_by varchar(255);
ALTER TABLE staff_accounts ADD COLUMN IF NOT EXISTS created_at timestamp(6) with time zone;

CREATE TABLE IF NOT EXISTS account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    account_type varchar(255) NOT NULL CHECK (account_type IN ('CHECKING', 'SAVINGS', 'MONEY_MARKET')),
    account_number varchar(255) NOT NULL UNIQUE,
    routing_number varchar(255) NOT NULL,
    available_balance numeric(19,2)
);
CREATE INDEX IF NOT EXISTS ix_account_user_id ON account (user_id);
